def p(text="", bold=False, align=None):
    x=doc.add_paragraph()
    if align is not None: x.alignment=align
    r=x.add_run(text); r.bold=bold; r.font.name="Times New Roman"; r.font.size=Pt(14)
    return x

def h(text, level=1):
    doc.add_heading(text, level=level)

def shade(cell, fill="D9EAF7"):
    tcPr=cell._tc.get_or_add_tcPr()
    shd=OxmlElement("w:shd"); shd.set(qn("w:fill"),fill); tcPr.append(shd)

def set_cell(cell,text,bold=False):
    cell.text=""
    para=cell.paragraphs[0]
    r=para.add_run(text); r.bold=bold; r.font.name="Times New Roman"; r.font.size=Pt(10)
    cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER

def table(headers, rows, widths=None):
    t=doc.add_table(rows=1, cols=len(headers))
    t.alignment=WD_TABLE_ALIGNMENT.CENTER
    t.style="Table Grid"
    for i,x in enumerate(headers):
        set_cell(t.rows[0].cells[i],x,True); shade(t.rows[0].cells[i])
    for row in rows:
        cells=t.add_row().cells
        for i,x in enumerate(row): set_cell(cells[i],str(x))
    if widths:
        for row in t.rows:
            for i,w in enumerate(widths): row.cells[i].width=Cm(w)
    doc.add_paragraph()
    return t

